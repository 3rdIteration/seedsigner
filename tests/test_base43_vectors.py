@pytest.mark.parametrize("hex_data, base43", BASE43_CASES)
def test_base43_roundtrip_basic(hex_data, base43):
    data = binascii.unhexlify(hex_data) if hex_data else b""
    assert base43_encode(data) == base43
    assert base43_decode(base43) == data


def test_base43_psbt_vector():
    expected = DecodeQR.base43_decode(PSBT_BASE43)
    assert base43_decode(PSBT_BASE43) == expected
    assert base43_encode(expected) == PSBT_BASE43


@pytest.mark.parametrize("base43", ELECTRUM_CASES)
def test_base43_electrum_cases(base43):
    expected = DecodeQR.base43_decode(base43)
    assert base43_decode(base43) == expected
    assert base43_encode(expected) == base43


@pytest.mark.parametrize("invalid", ["*" * 10 + "?", "hello%world"])
def test_base43_invalid_character(invalid):
    with pytest.raises(ValueError):
        base43_decode(invalid)
